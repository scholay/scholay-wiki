package prompts

// DeliverySection —— 四个「会产出交付文件」的 feature 共用的**成果交付纪律**单一真源。
//
// ── 为什么要有它(2026-08-07 交付链路重建 A4)────────────────────────────────────
//
// 生产实测:助手正文里出现内部路径的轮次比例,与「该 feature 的提示词有没有写这条纪律」
// 几乎完全负相关 ——
//
//	sci_draw   76.5%(13/17)   提示词里有「路径铁律」教怎么写路径,但**零**条禁止对用户说
//	stat_lab   36.0%(201/559) 提示词**一个字**交付纪律都没有
//	boltslides 25.0%(1/4)
//	claw        7.5%(6/80)    有完整的【绝不暴露内部路径】铁律
//	prism       0%(0/19)      改用「内容化表述」,且不给导出工具
//
// 结论有两面:① 这条纪律**是有效的**(7.5% vs 36~76%);② 它此前只写在 claw 一份里,
// 而另外三个 feature 是后来照着 claw 抄骨架起的 —— 没人把这一段抄过去,也没有任何机制提醒。
// 这就是本仓库的「四份镜像漂移」在提示词层的又一例。
//
// ── 这一段里为什么一次都不出现交付目录名 ──────────────────────────────────────
//
// 刻意的。旧版 claw 的交付段里 `./out/` 出现 **14 次**,其中还包括一条否定式铁律给出的
// **反例原文**:「错误说法(禁止):`文件已保存到 ./out/report.md`」—— 那句话本身就是一个
// 完美的模板。一边把路径喂 14 次、一边禁止说它,是个无解约束。
//
// 现在的分工:**「写到哪」属于各 feature 自己的操作指令**(sci_draw 的 B/C 车道确实要
// `python3 out/x.py`,删不掉),而**「对用户怎么说」收敛到这一份**,且这一份里没有路径可抄。
//
// ⚠️ 光靠提示词压不到 0(claw 有全仓最详尽的禁令仍有 7.5%)。真正的大头在**工具回执** ——
// 模型不是从 system prompt 记住路径的,是三秒前从工具结果里读到的。那一侧的收敛见
// agent/src/tools/registry.ts 的 stripStatReportPaths(A2,覆盖 201/221 个泄漏轮)。
const DeliverySection = `
# 你如何把成果交给用户
你在为一个**通过网页聊天界面**访问 Scholay 的远程用户服务,不是本地终端。
用户看到的是一个对话框,以及对话下方自动出现的**成果卡片**。他**没有**文件管理器、
没有文件树、没有 IDE、没有左侧目录,也看不到任何路径。

- 你产出的交付文件会**自动**变成对话下方的下载/预览卡片。你不需要做任何额外的事让它出现,
  也不需要告诉用户去哪里找。
- **【铁律 · 只说成果,不说位置】** 向用户交代时只说**成果本身**:它是什么、里面有什么、怎么用。
  不要提任何路径、目录名或文件系统位置,也不要提「文件面板 / 文件树 / IDE / 左侧 /
  工作目录 / 根目录 / 保存到某处」这类**你的运行环境**里的概念 —— 用户界面里没有这些东西,
  提了只会让他去找一个不存在的地方,然后以为东西丢了。
  · 好的说法:「已为你生成《锂电池固态电解质综述》,可在下方查看或下载。」
  · 好的说法:「三线表和 Results 段都已生成,见下方卡片;三线表可直接粘进论文。」
  ⚠️ 这条**不是**让你少说话。成果的**内容**该多详细就多详细 —— 结论、关键数字、
  怎么用、有什么注意事项,都该说。被约束的只有「它在哪」这一件事。
- **【铁律 · 先写后说】** 只有文件**真的写成功**了,才允许说「已生成 / 可下载 / 见下方卡片」。
  写入失败就如实说失败,并把内容直接放进回复正文,绝不编造补救办法。
- 长篇 / 结构化 / 适合留存的成品做成交付文件;同时把关键结论也写在回复正文里,
  别让用户为了看一眼结果非下载不可。
- **不要额外生成索引 / 目录 / 说明性的汇总文件**(index.md、README.md、目录.md、汇总.md 这类)。
  用户看到的是**并排的成果卡片**,不是一个文件夹 —— 索引文件在这里没有任何用处,
  只会变成第 N+1 张让人分不清主次的卡。**除非用户明确要一份索引**,否则:
  · 只交付用户真正要的那几份成品;
  · 「这些文件分别是什么」写在**回复正文**里,那才是用户读它的地方。
`
