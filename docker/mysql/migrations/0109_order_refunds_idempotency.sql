-- ============================================================================
-- 0109 退款的**真**幂等键
--
-- 🔴 0107/0108 声称「refund_no = RF{订单号}-{已有笔数+1},重复提交撞唯一索引被挡掉」——
--    这个说法是错的,而且是结构性的错:
--    退款事务第一步就对订单行 `SELECT ... FOR UPDATE`,两次提交必然**串行**;
--    第二次进来时那个 COUNT(*) 已经能读到第一笔,于是序号前进成 -2,
--    与第一笔的 -1 根本不冲突 —— uk_refund_no 在这条路径上永远不会触发。
--
--    真实触发场景不是并发,是**重试**:退款请求打到后端并提交成功,但响应在 nginx
--    读超时(写操作 30s 硬超时)或管理员网络抖动时丢失;退款弹窗刻意「失败不关窗、
--    输入留着可重试」,管理员再点一次 —— 于是同一笔 ¥50 退款被登记两次,
--    经费按比例被回收两次,用户收到两封退款通知,而商户后台实际只退了一次。
--    (全额退侥幸被「剩余可退 <= 0」挡住,暴露面是**部分退款**。)
--
-- 修法:幂等键不能由服务端从计数派生,必须由**调用方**带入。
-- 前端在打开退款弹窗时生成一次 uuid,整个弹窗生命周期内复用(重试沿用同一个),
-- 后端把它写进本列并靠唯一索引挡住第二次写入。
-- ============================================================================

CALL add_column_if_not_exists('order_refunds', 'idempotency_key',
  "VARCHAR(64) NOT NULL DEFAULT '' COMMENT '调用方生成的幂等键(前端每次打开退款弹窗生成一次);空串=历史数据'");

-- ⚠️ 用**普通唯一索引**而不是简单 UNIQUE 的原因:
-- MySQL 的唯一索引把 NULL 视为互不相等(可重复),但空串 '' 不是 NULL —— 会互相冲突。
-- 历史行的 idempotency_key 是 '',若直接建唯一索引,第二条历史行就插不进去/建索引失败。
-- 所以这里先把历史行回填成各自唯一的值(用 refund_no,它本身唯一),再建唯一索引。
UPDATE `order_refunds` SET `idempotency_key` = `refund_no` WHERE `idempotency_key` = '';

CALL add_index_if_not_exists('order_refunds', 'uk_idempotency_key', '`idempotency_key`', TRUE);
