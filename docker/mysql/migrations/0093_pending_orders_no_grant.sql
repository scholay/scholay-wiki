-- ============================================================================
-- 0093: 在途(未支付)订阅单的赠送经费归零
--
-- 为什么需要这条(部署顺序里最容易吞钱的一处):
--   履约 activateSubscriptionInTx 读的是**订单行上冻结的** credits_granted,不是当前配置。
--   所以「建单侧改成不再赠送」对**部署前已经建好、还没支付**的 pending 订阅单完全无效 ——
--   它们支付时仍会按订单上那个数发放经费。0090 之后临时经费那张表已经没人读,
--   赠送就会落进一张死表 = 用户付了钱、权益静默消失。
--
--   代码侧已经硬置 0(履约不再读 ord.CreditsGranted 走赠送路径),这条迁移是**第二道保险**:
--   把账面也抹平,免得后台订单列表/对账/客诉时看到一个「承诺了但没发」的数。
--
-- 只动 subscription 且 status='pending' 的单:
--   - 已支付(paid)的历史单**不改** —— 那是已履约的事实,改了就是篡改账本;
--   - 充值单(order_type='recharge')的 credits_granted 是**到账经费**,与赠送无关,绝不能碰。
--
-- 幂等:WHERE credits_granted <> 0 使重放为 no-op(第二次匹配 0 行)。
-- ============================================================================

UPDATE `orders`
SET `credits_granted` = 0
WHERE `order_type` = 'subscription'
  AND `status` = 'pending'
  AND `credits_granted` <> 0;
