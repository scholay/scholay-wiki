-- ============================================================================
-- 0110 兑换码的授予**单位**(天 / 自然月 / 自然年)
--
-- 此前兑换码只有 grant_days(天),管理员没法发「1 个月会员」「1 年会员」——
-- 只能填 30 / 365 近似,而那与用户**购买**同样时长拿到的到期日并不相等
-- (购买走 AddPeriod 的真自然月/年;30 天在 2 月多给、在 1 月少给)。
--
-- 🔴 **DEFAULT 'day' 是存量码语义不变的全部保证**。
--    库里已发出去的码 grant_days=30 的含义就是「30 天」;若 DEFAULT 写成别的、
--    或漏了 DEFAULT 让它变成空串/NULL,那些码在新代码里会落进未知分支,
--    最坏情况是被当成「30 个月」发出去(约 2.5 年)。
--    因此这里**不需要任何回填 UPDATE** —— DEFAULT 一到位,存量行自动保持原语义。
--
-- 列名用 grant_unit 而不是 grant_period:包里 "period" 已被 AddPeriod / prorationDays
-- 占用为「计费周期(月付/年付)」语义,复用会制造歧义。
--
-- ⚠️ 绝不 DROP / 改 grant_days 列 —— 它继续承载「数量」,只是含义由 grant_unit 决定。
-- ============================================================================

CALL add_column_if_not_exists('vip_redemption_codes', 'grant_unit',
  "VARCHAR(8) NOT NULL DEFAULT 'day' COMMENT '授予单位 day|month|year —— grant_days 是它的数量;存量码一律 day'");

-- 不加索引:没有按单位筛选的查询,加了只是白付写入成本。
