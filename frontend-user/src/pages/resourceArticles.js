// 根据 slug 获取文章
export const getArticleBySlug = (slug) => {
  return resourceArticles.find(a => a.slug === slug) || null;
};

// 获取相关文章（同分类，排除自身）
export const getRelatedArticles = (slug, limit = 3) => {
  const current = getArticleBySlug(slug);
  if (!current) return resourceArticles.slice(0, limit);
  
  const sameCategory = resourceArticles.filter(
    a => a.category === current.category && a.slug !== slug
  );
  const others = resourceArticles.filter(
    a => a.category !== current.category && a.slug !== slug
  );
  
  return [...sameCategory, ...others].slice(0, limit);
};

export default resourceArticles;
