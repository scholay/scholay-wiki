import axios from 'axios';

// Use relative path so requests go through Nginx reverse proxy
// In production, this will be '' (empty), making requests to /api/v1/*
// In development, you can set REACT_APP_API_URL=http://localhost:8080 for direct backend access
const API_URL = process.env.REACT_APP_API_URL || '';

const api = axios.create({
  baseURL: `${API_URL}/api/v1`,
  headers: {
    'Content-Type': 'application/json',
  },
});

// Request interceptor to add auth token
api.interceptors.request.use(
  (config) => {
    const token = localStorage.getItem('user_token');
    if (token) {
      config.headers.Authorization = `Bearer ${token}`;
    }
    return config;
  },
  (error) => {
    return Promise.reject(error);
  }
);

// Response interceptor to handle errors
api.interceptors.response.use(
  (response) => response,
  (error) => {
    // 处理 401 (未授权) 和 403 (禁止访问) 错误
    if (error.response?.status === 401 || error.response?.status === 403) {
      // Unauthorized/Forbidden - clear token and state
      localStorage.removeItem('user_token');
      localStorage.removeItem('user_data');

      // Show notification to user
      const message = error.response?.data?.message ||
        (error.response?.status === 403 ? '访问被拒绝，请重新登录' : '登录已失效，请重新登录');

      // Dispatch custom event with message
      window.dispatchEvent(new CustomEvent('auth:expired', {
        detail: { message }
      }));

      // Redirect to home page immediately if not already there
      if (window.location.pathname !== '/') {
        window.location.href = '/';
      }
    }
    return Promise.reject(error);
  }
);

