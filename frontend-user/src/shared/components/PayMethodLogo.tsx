import { forwardRef } from 'react';
import { Zap } from 'lucide-react';
import { cn } from '@/shared/lib/utils';

/**
 * 支付渠道品牌 logo —— 收银台里「微信支付 / 支付宝」的官方标识。
 *
 * 为什么单独立一个组件,而不是复用 ProviderLogo:
 *   - ProviderLogo 服务的是**第三方账号登录**(GitHub / Google / 微信开放平台 …),
 *     它的默认策略是 monochrome currentColor,与我们的灰阶 UI 融为一体。
 *   - 支付渠道**恰恰相反,必须保持品牌本色**。微信支付《物料管理规范》明确要求
 *     商户在收银台等界面「平等充分展示官方标识,不得以任何方式遮挡或弱化」;
 *     而且支付场景下「一眼认出是微信还是支付宝」本身就是要传达的信息 ——
 *     两个都染成品牌红的通用图标(此前是 lucide 的 QrCode / CreditCard)等于没有标识。
 *   - 所以这里的 logo **不随选中态改色**。选中反馈交给外层的边框 / 底色 / 单选点,
 *     不动 logo 本身。
 *
 * 品牌色(2026-08-03 核对):
 *   - 微信       #07C160(微信 2021 起的品牌绿)
 *   - 支付宝     #1677FF(支付宝 2020 品牌升级后的亮蓝)
 *
 * path 数据来自 Simple Icons(其 SVG 源自各家官方品牌资源),viewBox 统一 24×24,
 * 与 ProviderLogo 同款约定;尺寸由调用方 className 控制。
 *
 * ⚠️ 若需要**像素级官方物料**(带 wordmark 的组合标、指定留白比例等),
 * 需到 https://pay.weixin.qq.com/material 与 https://design.alipay.com/resource
 * 下载(前者需商户登录)。届时只改本文件即可,四处调用点不用动。
 *
 * 用法:
 *   <PayMethodLogo method="wechat" className="size-5" />
 */

export type PayMethod = 'wechat' | 'alipay' | 'test';

interface PayMethodLogoProps {
  method: string;
  className?: string;
}

/** 官方品牌色 —— 只在本文件出现,已在设计护栏的品牌 logo 白名单内。 */
